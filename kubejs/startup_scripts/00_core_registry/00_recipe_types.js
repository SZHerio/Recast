// Типы рецептов собственных машин. Вынесены в отдельный файл с ранним
// префиксом: GregTech создаёт машину со ссылкой на тип рецепта, и тип обязан
// быть зарегистрирован раньше.

// Водоочистная станция — первая собственная машина сборки.
//
// До этого момента Recast только переписывал чужие рецепты: восемь волн, ни
// одной своей машины. При этом коммунальная водная линия — сырая вода,
// техническая, питьевая, стоки, осадок и биогаз — была обещана игроку ещё в
// четвёртой эпохе и всё это время держалась на тексте и правилах. Здесь она
// получает агрегат.
//
// Почему мультиблок, а не простая машина: очистка воды — это не станок, а
// сооружение. Оно занимает место, требует планировки и видно издалека. Ровно
// того же требует от игрока городской контракт на водопровод.
//
// Почему средствами GregTech, а не отдельным модом: у сборки один владелец
// промышленной механики. Заводить второй ради пяти машин значит повторить ту
// самую ошибку, которую сборка исправляет у чужих модов.
//
// Чертёж: куб три на три на три. Контроллер стоит по центру передней стены,
// в самом центре сооружения — фильтрующий корпус, углы и стены собираются из
// водонепроницаемых корпусов, окна — из закалённого стекла. Хатчи ставятся
// вместо любого блока стены: их разрешает autoAbilities.
//
// Все имена блоков, текстур, звуков и наложений сверены с JAR gtceu 7.5.3.
GTCEuStartupEvents.registry('gtceu:recipe_type', (event) => {
  event.create('water_treatment')
    .category('water_treatment_category')
    .setEUIO('in')
    // Вход: до двух предметов и до двух жидкостей — вода и реагент, например
    // хлор или коагулянт. Выход: до двух предметов и до трёх жидкостей, потому
    // что очистка всегда даёт больше одного потока — чистую воду, оборотную и
    // осадок. Это прямо следует из правила четвёртой эпохи об обязательном
    // стоке: воду нельзя очистить «в никуда».
    .setMaxIOSize(2, 2, 2, 3)
    .setSlotOverlay(false, false, GuiTextures.FILTER_SLOT_OVERLAY)
    .setProgressBar(GuiTextures.PROGRESS_BAR_BATH, FillDirection.LEFT_TO_RIGHT)
    .setSound(GTSoundEntries.BATH)
})