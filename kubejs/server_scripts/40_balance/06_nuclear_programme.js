function ifM6State(server) {
  const root = server.persistentData
  if (!root.contains('industrial_frontier')) root.put('industrial_frontier', {})
  const state = root.get('industrial_frontier')
  if (!state.contains('m6_nuclear')) state.put('m6_nuclear', {})
  return state.get('m6_nuclear')
}

ServerEvents.customCommand('if_nuclear_contract', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM6State(event.server)
  const status = state.contains(IF_M6_CONTRACT.id) ? state.getString(IF_M6_CONTRACT.id) : 'доступен'

  player.tell(`[P${IF_M6_CONTRACT.min_epoch}] ${IF_M6_CONTRACT.title_ru} (${IF_M6_CONTRACT.kind_ru}) — ${status}`)
  IF_M6_CONTRACT.demand_ru.forEach((line) => player.tell(`    требует: ${line}`))
  player.tell(`    награда: ${IF_M6_CONTRACT.reward_ru}`)
  player.tell(`    автоматизация: ${IF_M6_CONTRACT.requires_automation_ru}`)
  player.tell(`    отказ: ${IF_M6_CONTRACT.refusal_ru}`)
})

ServerEvents.customCommand('if_nuclear_safety', (event) => {
  const player = event.player
  if (!player) return
  player.tell('Регламент безопасности атомного объекта:')
  IF_M6_SAFETY.forEach((rule) => {
    player.tell(` ${rule.title_ru}`)
    player.tell(`    ${rule.rule_ru}`)
  })
  player.tell('Порядок не меняется: сначала измерение и защита, потом пуск.')
})

ServerEvents.customCommand('if_nuclear_operations', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM6State(event.server)
  player.tell('Операции вокруг атомной программы:')
  IF_M6_OPERATIONS.forEach((operation) => {
    const status = state.contains(operation.id) ? state.getString(operation.id) : 'не начата'
    player.tell(` ${operation.title_ru} — ${status}`)
    player.tell(`    начинается: ${operation.trigger_ru}`)
    player.tell(`    на кону: ${operation.stake_ru}`)
    player.tell(`    переговоры: ${operation.negotiation_ru}`)
    player.tell(`    восстановление: ${operation.recovery_ru}`)
  })
  player.tell('Стратегическое вооружение через лут и торговлю не выдаётся ни в одной операции.')
})
