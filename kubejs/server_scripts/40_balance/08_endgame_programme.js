function ifM8State(server) {
  const root = server.persistentData
  if (!root.contains('industrial_frontier')) root.put('industrial_frontier', {})
  const state = root.get('industrial_frontier')
  if (!state.contains('m8_endgame')) state.put('m8_endgame', {})
  return state.get('m8_endgame')
}

// Оба мегапроекта поднимают городские показатели, как контракты предыдущих
// эпох. Сфера трогает энергию и оборону, колония — продовольствие и транспорт:
// она снимает с Земли зависимость и одновременно требует регулярного рейса.
const IF_M8_CONTRACT_SIGNALS = {
  dyson_swarm: ['energy', 'defence'],
  proxima_colony: ['food', 'transport', 'energy']
}

ServerEvents.customCommand('if_megaprojects', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM8State(event.server)
  player.tell('Финальные мегапроекты. Их два, и они проверяют разное:')
  IF_M8_MEGAPROJECTS.forEach((project) => {
    const status = state.contains(project.id) ? state.getString(project.id) : 'доступен'
    player.tell(` [P${project.min_epoch}] ${project.title_ru} (${project.kind_ru}) — ${status}`)
    project.demand_ru.forEach((line) => player.tell(`    требует: ${line}`))
    player.tell(`    награда: ${project.reward_ru}`)
    player.tell(`    автоматизация: ${project.requires_automation_ru}`)
    player.tell(`    отказ: ${project.refusal_ru}`)
    player.tell(`    поднимает показатели: ${(IF_M8_CONTRACT_SIGNALS[project.id] || []).join(', ')}`)
  })
  player.tell('Строить можно оба или любой один: это два разных финала, а не две половины одного.')
})

ServerEvents.customCommand('if_planetary_network', (event) => {
  const player = event.player
  if (!player) return
  player.tell('Планетарная сеть — планеты как цеха одного завода:')
  IF_M8_PLANETARY_NETWORK.forEach((rule) => {
    player.tell(` ${rule.title_ru}`)
    player.tell(`    ${rule.rule_ru}`)
  })
  player.tell('Орбитальные службы — что даёт орбита сверху:')
  IF_M8_ORBITAL_SERVICES.forEach((service) => {
    player.tell(` ${service.title_ru}`)
    player.tell(`    даёт: ${service.gives_ru}`)
    player.tell(`    стоит: ${service.costs_ru}`)
  })
})

