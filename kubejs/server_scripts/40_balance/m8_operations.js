function ifM8OperationState(server) {
  const root = server.persistentData
  if (!root.contains('industrial_frontier')) root.put('industrial_frontier', {})
  const state = root.get('industrial_frontier')
  if (!state.contains('m8_operations')) state.put('m8_operations', {})
  return state.get('m8_operations')
}

ServerEvents.customCommand('if_endgame_bases', (event) => {
  const player = event.player
  if (!player) return
  const base = IF_M8_BASE_LEVEL
  player.tell(`${base.level} — ${base.title_ru} (эпохи P${base.min_epoch}–P${base.max_epoch})`)
  player.tell(`    состав: ${base.rooms_ru}`)
  player.tell(`    лут: ${base.loot_ru}`)
  player.tell(`    не выпадает: ${base.forbidden_ru}`)
})

ServerEvents.customCommand('if_endgame_operations', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM8OperationState(event.server)
  player.tell('Операции финала:')
  IF_M8_OPERATIONS.forEach((operation) => {
    const status = state.contains(operation.id) ? state.getString(operation.id) : 'не начата'
    player.tell(` ${operation.title_ru} — ${status}`)
    player.tell(`    начинается: ${operation.trigger_ru}`)
    player.tell(`    на кону: ${operation.stake_ru}`)
    player.tell(`    переговоры: ${operation.negotiation_ru}`)
    player.tell(`    восстановление: ${operation.recovery_ru}`)
  })
})

ServerEvents.customCommand('if_endgame_resolutions', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM8OperationState(event.server)
  const chosen = state.contains('resolution') ? state.getString('resolution') : 'не выбрана'
  player.tell(`Развязка: ${chosen}. Четыре варианта, ни один не лучший:`)
  IF_M8_RESOLUTIONS.forEach((resolution) => {
    player.tell(` ${resolution.title_ru}`)
    player.tell(`    ${resolution.means_ru}`)
  })
  player.tell('Развязка меняет то, как живёт регион, и не закрывает доступ ни к одной части игры.')
})
