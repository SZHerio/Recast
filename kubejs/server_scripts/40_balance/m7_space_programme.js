function ifM7SpaceState(server) {
  const root = server.persistentData
  if (!root.contains('industrial_frontier')) root.put('industrial_frontier', {})
  const state = root.get('industrial_frontier')
  if (!state.contains('m7_space')) state.put('m7_space', {})
  return state.get('m7_space')
}

ServerEvents.customCommand('if_spaceport_contract', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM7SpaceState(event.server)
  const status = state.contains(IF_M7_SPACEPORT.id) ? state.getString(IF_M7_SPACEPORT.id) : 'доступен'

  player.tell(`[P${IF_M7_SPACEPORT.min_epoch}] ${IF_M7_SPACEPORT.title_ru} (${IF_M7_SPACEPORT.kind_ru}) — ${status}`)
  IF_M7_SPACEPORT.demand_ru.forEach((line) => player.tell(`    требует: ${line}`))
  player.tell(`    награда: ${IF_M7_SPACEPORT.reward_ru}`)
  player.tell(`    автоматизация: ${IF_M7_SPACEPORT.requires_automation_ru}`)
  player.tell(`    отказ: ${IF_M7_SPACEPORT.refusal_ru}`)
})

// Связь с городскими показателями, как у региональных контрактов P5. Значение
// поднимает подтверждённое закрытие, а не прожитое время. Космодром трогает три
// показателя сразу, и это не щедрость: он требует транспортной связности, чтобы
// подвозить ступени, энергетического ввода с резервом и режима вокруг зоны
// отчуждения — то есть уже опирается на все три, когда сдаётся.
const IF_M7_CONTRACT_SIGNALS = {
  city_spaceport: ['transport', 'energy', 'defence']
}

ServerEvents.customCommand('if_spaceport_signals', (event) => {
  const player = event.player
  if (!player) return
  const affected = IF_M7_CONTRACT_SIGNALS[IF_M7_SPACEPORT.id] || []
  player.tell(`${IF_M7_SPACEPORT.title_ru} поднимает показатели: ${affected.join(', ')}`)
  player.tell('Показатели хранит Threat Director; операции опираются на них, а не на возраст мира.')
})

