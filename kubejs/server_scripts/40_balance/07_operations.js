function ifM7OperationState(server) {
  const root = server.persistentData
  if (!root.contains('industrial_frontier')) root.put('industrial_frontier', {})
  const state = root.get('industrial_frontier')
  if (!state.contains('m7_operations')) state.put('m7_operations', {})
  return state.get('m7_operations')
}

ServerEvents.customCommand('if_late_squads', (event) => {
  const player = event.player
  if (!player) return
  player.tell('Поздние комплекты отрядов (P7):')
  IF_M7_FACTIONS.forEach((faction) => {
    player.tell(` ${faction.title_ru}: ${faction.squad_ru}`)
  })
  player.tell('Потолок снаряжения — эпоха команды. Шанс выпадения оружия 15%, готовое изделие будущей эпохи не выпадает.')
})

ServerEvents.customCommand('if_late_bases', (event) => {
  const player = event.player
  if (!player) return
  const base = IF_M7_BASE_LEVEL
  player.tell(`${base.level} — ${base.title_ru} (эпохи P${base.min_epoch}–P${base.max_epoch})`)
  player.tell(`    состав: ${base.rooms_ru}`)
  player.tell(`    лут: ${base.loot_ru}`)
  player.tell(`    не выпадает: ${base.forbidden_ru}`)
  player.tell('Допуски на ваш объект:')
  IF_M7_CLEARANCES.forEach((clearance) => {
    player.tell(` ${clearance.title_ru}`)
    player.tell(`    ${clearance.meaning_ru}`)
  })
})

ServerEvents.customCommand('if_late_operations', (event) => {
  const player = event.player
  if (!player) return
  const state = ifM7OperationState(event.server)
  player.tell('Операции седьмой эпохи:')
  IF_M7_OPERATIONS.forEach((operation) => {
    const status = state.contains(operation.id) ? state.getString(operation.id) : 'не начата'
    player.tell(` ${operation.title_ru} — ${status}`)
    player.tell(`    начинается: ${operation.trigger_ru}`)
    player.tell(`    на кону: ${operation.stake_ru}`)
    player.tell(`    переговоры: ${operation.negotiation_ru}`)
    player.tell(`    восстановление: ${operation.recovery_ru}`)
  })
  player.tell(` ${IF_M7_CHARGE_RESPONSE.title_ru}`)
  player.tell(`    охват: ${IF_M7_CHARGE_RESPONSE.scope_ru}`)
  player.tell(`    длительность: ${IF_M7_CHARGE_RESPONSE.duration_ru}`)
  player.tell(`    предел: ${IF_M7_CHARGE_RESPONSE.limit_ru}`)
})
