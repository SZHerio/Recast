// Подсказки на предметах, вокруг которых сборка приняла решение, отличающееся
// от привычного. Игрок не обязан читать документацию, чтобы понять, почему
// знакомый рецепт исчез или ведёт себя иначе, — ответ лежит на самом предмете.
//
// ItemEvents.tooltip и метод add подтверждены в kubejs-forge-2001.6.5-build.26.
ItemEvents.tooltip((tooltip) => {
  const grey = (line) => Text.gray(line)
  const amber = (line) => Text.gold(line)

  // P1: точка входа в механику намеренно дешёвая.
  tooltip.add('create:andesite_alloy', [
    amber('Точка входа в P1'),
    grey('Сборка не берёт пошлину за право начать механизацию.')
  ])

  // P2: два маршрута к одной форме, разведённые по роли.
  tooltip.add(['create:iron_sheet', 'create:copper_sheet', 'create:golden_sheet'], [
    amber('Объёмный маршрут'),
    grey('Лист Create и пластина GregTech принимаются одним тегом.'),
    grey('Create даёт объём дёшево, GregTech — точность.')
  ])

  // Латунь: единый состав вместо двух конкурирующих.
  tooltip.add('gtceu:brass_ingot', [
    amber('Cu₃Zn — единый состав'),
    grey('Три меди и один цинк дают четыре слитка.'),
    grey('Рецепт Create «один к одному» удалён: он спорил с металлургией.')
  ])

  // Руда: почему исчезло дробление Create.
  tooltip.add(['minecraft:raw_iron', 'minecraft:raw_copper', 'minecraft:raw_gold'], [
    amber('Один владелец геологии'),
    grey('Дробление руды в Create отключено: оно давало второй, более'),
    grey('дешёвый путь к тому же металлу. Жилы GregTech — единственный источник.')
  ])

  // Сталь: рубеж эпохи, а не просто сплав.
  tooltip.add('gtceu:steel_ingot', [
    amber('Рубеж P2'),
    grey('Сталь открывает электрификацию и вход в огнестрельный домен.'),
    grey('Получить её обжигом железа нельзя — только металлургией.')
  ])

  // Вода: три класса, которые нельзя путать.
  tooltip.add('minecraft:water_bucket', [
    amber('Сырая вода'),
    grey('Годится для охлаждения и стройки.'),
    grey('Химия требует техническую, городской рацион — питьевую.')
  ])

  // AE2: домен отложен до P5 намеренно.
  tooltip.add(['ae2:certus_quartz_crystal', 'ae2:fluix_crystal'], [
    amber('Цифровая фабрика — это P5'),
    grey('Семь входных рецептов AE2 закрыты до своей эпохи,'),
    grey('чтобы склад не появился раньше производства, которое он обслуживает.')
  ])

  // Стрессометр: прибор, который экономит часы.
  tooltip.add('create:stressometer', [
    amber('Смотрите до подключения'),
    grey('Запас усилия общий на всю сеть: перегрузка останавливает всё сразу.')
  ])
})
